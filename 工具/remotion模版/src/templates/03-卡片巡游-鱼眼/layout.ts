/** 某一刻一张卡片的姿势。dx、dy 是镜头的漂移，加在位置上。 */
export const poseAt = (table: Table, t: number, dx = 0, dy = 0): Pose => ({
  x: track(t, table.x) + dx,
  y: track(t, table.y) + dy,
  s: track(t, table.s),
  rx: track(t, table.rx),
  ry: track(t, table.ry),
  rz: track(t, table.rz),
  blur: track(t, table.blur),
});

