/** 几个时间点（帧）。前三站各有一张主角卡，第四站是总览。 */
export type Times = {
  intro: number; // 开场的总览到这一帧为止，之后镜头飞向第一张主角卡
  a: [number, number, number, number]; // 每一站的主角落定、标题开始弹出的帧
  u: [number, number, number]; // 前三站开始离开的帧。第四站不离开
  f0: number; // 总览的卡片开始归位的帧
  f1: number; // 总览的卡片都归位的帧
};

export const timesFor = (p: TemplateProps): Times => {
  const [s0, s1, s2, s3] = p.stations;
  const a: Times['a'] = [s0.at, s1.at, s2.at, s3.at];
  const u: Times['u'] = [s0.until ?? s0.at + 20, s1.until ?? s1.at + 16, s2.until ?? s2.at + 16];
  return {intro: s0.at - p.introTravel, a, u, f0: u[2] + 1, f1: s3.at - 3};
};

